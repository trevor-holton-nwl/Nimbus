// Golden capture for the optimizer worker contract: records one OptimizerWorkerRequest together with the
// OptimizerWorkerResponse the engine produces for it, as a JSON file a test can replay. These pairs are the
// safety net for the headless optimizer (Jobs scheduler): the Node entry must reproduce the browser worker's
// patches for the same snapshot.
//
// Dates are written as {"$d": "<ISO instant>"} and Sets as {"$set": [...]}, so a pair round-trips exactly.
// Fixtures are generated and replayed with TZ=UTC: the engine reads naive plant wall-clock values through local
// Date getters, so the process zone is part of the input.
//
// Usage (repo root, after `npm run build`):
//   TZ=UTC node scripts/capture-optimizer-golden.mjs --synthetic basic --out tests/modules/fixtures/optimizer-golden/synthetic-basic.json
//   TZ=UTC node scripts/capture-optimizer-golden.mjs --request request.json --out pair.json
//
// Capturing a REAL pair from a browser session (DevTools console on the Gantt tab, before pressing Run):
//   const enc = (k, v) => (v instanceof Date ? { $d: v.toISOString() } : v instanceof Set ? { $set: [...v] } : v);
//   const post = Worker.prototype.postMessage, seen = {};
//   Worker.prototype.postMessage = function (m) {
//     if (m && m.runId && m.snapshot) { seen[m.runId] = JSON.stringify(m, enc);
//       this.addEventListener('message', e => { if (e.data.runId === m.runId && e.data.candidate)
//         console.log(JSON.stringify({ request: JSON.parse(seen[m.runId]), response: e.data }, enc)); }); }
//     return post.apply(this, arguments);
//   };
// Save the logged text to a file and feed it back with --pair, or pass only its `request` to --request.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const { encodeTagged, decodeTagged } = await import('../frontend/optimization/headless-codec.mjs');

/** Serialise any request/response graph. Dates become {"$d": iso}, Sets {"$set": [...]}. */
export const encodeGolden = value => encodeTagged(value, 2);

/** Inverse of encodeGolden. */
export const decodeGolden = text => decodeTagged(text);

/** Install the compute core the engine delegates to (a browser loads it as a classic script first). */
export function ensureComputeCore() {
  if (globalThis.NimbusComputeCore) return;
  const require = createRequire(import.meta.url);
  globalThis.NimbusComputeCore = require('../frontend/nimbus-compute-core.js');
}

/** Run one request through the worker entry and return the recorded pair. `clock` is the deadline clock. */
export async function recordGolden(request, clock = () => performance.now()) {
  ensureComputeCore();
  const { buildOptimizerWorkerResponse } = await import('../frontend/optimization/optimizer-worker.mjs');
  const response = buildOptimizerWorkerResponse(request, clock);
  return { request, response };
}

/** The synthetic fixtures: small enough that the search finishes exactly, long before any deadline. */
export async function syntheticRequest(name) {
  if (name !== 'basic') throw new Error(`unknown synthetic fixture: ${name}`);
  const { scenarioSnapshot, at } = await import('../tests/modules/helpers/order-rules-fixture.mjs');
  const snapshot = scenarioSnapshot({
    tasks: [
      { id: 'A', run: 2, color: 'GREEN', due: '2035-08-07T18:00:00' },
      { id: 'B', run: 3, color: 'BLUE', due: '2035-08-07T18:00:00' },
      { id: 'C', run: 2, color: 'GREEN', due: '2035-08-08T18:00:00' },
      { id: 'D', run: 4, color: 'BLUE', due: '2035-08-09T18:00:00' },
    ],
  });
  return {
    runId: 'golden-synthetic-basic',
    mode: 'duedate',
    snapshot,
    request: {
      mode: 'duedate', plant: 'P1', respectFirmed: true, respectCalendar: true,
      planningStart: at('2035-08-06T08:00:00'), runNow: at('2035-08-06T08:00:00'), endDate: at('2035-08-20T18:00:00'),
    },
    // Far larger than the search needs: the run ends on convergence, so the result is deterministic.
    deadlineDurationMs: 600_000,
  };
}

async function main(argv) {
  const arg = name => { const i = argv.indexOf(`--${name}`); return i >= 0 ? argv[i + 1] : undefined; };
  const out = arg('out');
  if (!out) throw new Error('--out <file> is required');
  let request;
  if (arg('synthetic')) request = await syntheticRequest(arg('synthetic'));
  else if (arg('request')) request = decodeGolden(readFileSync(resolve(arg('request')), 'utf8'));
  else throw new Error('pass --synthetic <name> or --request <file>');
  const pair = await recordGolden(request);
  if (pair.response.error) throw new Error(`worker answered with an error: ${pair.response.error}`);
  mkdirSync(dirname(resolve(out)), { recursive: true });
  writeFileSync(resolve(out), `${encodeGolden({ _note: 'Generated by scripts/capture-optimizer-golden.mjs under TZ=UTC; do not edit.', ...pair })}\n`);
  process.stdout.write(`recorded ${pair.response.candidate?.patches?.length ?? 0} patches -> ${out}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).then(() => process.exit(0), error => { process.stderr.write(`${error.stack ?? error}\n`); process.exit(1); });
}
